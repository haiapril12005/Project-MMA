const fs = require('node:fs');
const path = require('node:path');
const { products, reviews } = require('../src/data/seed');

const quote = (value) => `'${String(value ?? '').replace(/'/g, "''")}'`;
const number = (value) => String(Number(value));
const textArray = (items) => `array[${items.map(quote).join(', ')}]::text[]`;

const productRows = products.map((product) => `(
  ${number(product.id)}, ${quote(product.name)}, ${number(product.price)}, ${quote(product.category)},
  ${quote(product.brand)}, ${textArray(product.color)}, ${quote(product.material)}, ${quote(product.dimensions)},
  ${quote(product.description)}, ${quote(product.uri)}, ${number(product.percentOff)}, ${number(product.stock)}
)`).join(',\n');

const reviewRows = reviews.map((review) => `(
  ${number(review.productId)}, null, ${quote(review.userName)}, ${number(review.rating)},
  ${quote(review.comment)}, ${quote(review.createdAt)}::timestamptz
)`).join(',\n');

const sql = `-- Generated by npm run supabase:seed. Contains products and anonymous sample reviews only.
begin;

insert into public.products (
  id, name, price, category, brand, colors, material, dimensions,
  description, image_url, percent_off, stock
) values
${productRows}
on conflict (id) do update set
  name = excluded.name,
  price = excluded.price,
  category = excluded.category,
  brand = excluded.brand,
  colors = excluded.colors,
  material = excluded.material,
  dimensions = excluded.dimensions,
  description = excluded.description,
  image_url = excluded.image_url,
  percent_off = excluded.percent_off,
  stock = excluded.stock;

delete from public.reviews where user_id is null;
insert into public.reviews (product_id, user_id, user_name, rating, comment, created_at) values
${reviewRows};

commit;
`;

const target = path.join(__dirname, '..', 'supabase', 'seed.sql');
fs.writeFileSync(target, sql);
console.log(`Đã tạo ${target}: ${products.length} sản phẩm, ${reviews.length} đánh giá mẫu.`);
