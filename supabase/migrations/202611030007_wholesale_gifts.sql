-- Giá sỉ + quà tặng theo giá trị đơn. Chạy SAU 202611030006_dashboard_deposits.sql.
-- 1. Giá sỉ: mua từ wholesale_min_qty cái (mặc định 3, cộng mọi màu) của CÙNG một sản phẩm thì mỗi cái
--    giảm thêm wholesale_percent (mặc định 10%) trên giá đang bán. Cửa hàng chỉnh từng sản phẩm trong bảng products.
-- 2. Quà tặng: bảng gift_rules (đơn từ min_total thì tặng product_id). Mỗi đơn nhận 1 quà ở mốc cao nhất đạt được,
--    tính trên tiền hàng sau giá sỉ (chưa gồm phí giao). Quà là một dòng đơn giá 0đ (is_gift = true), có trừ kho;
--    hết hàng thì bỏ qua quà đó. Hủy đơn thì kho của quà cũng được cộng lại.
-- Thứ tự tính tiền: giá bán -> giá sỉ -> quà tặng -> phí giao -> tổng -> cọc 30% nếu tổng từ 20 triệu.

-- ---------- Cột và bảng mới ----------
alter table public.products
  add column if not exists wholesale_min_qty integer not null default 3,
  add column if not exists wholesale_percent numeric(4, 3) not null default 0.10;
alter table public.products drop constraint if exists products_wholesale_check;
alter table public.products
  add constraint products_wholesale_check check (wholesale_min_qty >= 2 and wholesale_percent between 0 and 0.5);

alter table public.order_items add column if not exists is_gift boolean not null default false;

create table if not exists public.gift_rules (
  id bigint generated by default as identity primary key,
  min_total bigint not null check (min_total > 0),
  product_id bigint not null references public.products(id) on delete cascade,
  quantity integer not null default 1 check (quantity > 0),
  active boolean not null default true,
  unique (min_total, product_id)
);
alter table public.gift_rules enable row level security;
drop policy if exists "gift rules are publicly readable" on public.gift_rules;
create policy "gift rules are publicly readable" on public.gift_rules for select to anon, authenticated using (true);
revoke insert, update, delete on public.gift_rules from anon, authenticated;
grant select on public.gift_rules to anon, authenticated;

insert into public.gift_rules (min_total, product_id, quantity)
select rule.min_total, rule.product_id, 1
from (values (30000000::bigint, 35::bigint), (60000000::bigint, 33::bigint)) as rule(min_total, product_id)
where exists (select 1 from public.products where id = rule.product_id)
on conflict (min_total, product_id) do nothing;

-- ---------- Tính tiền đơn: giá sỉ, quà, phí giao, cọc, bảo hành ----------
create or replace function public.apply_furniture_terms(p_order_id uuid, p_zone text)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_fee bigint := public.delivery_fee(p_zone);
  v_item_total bigint;
  v_rule record;
  v_color text;
begin
  if v_fee is null then
    raise exception 'DELIVERY_ZONE_INVALID';
  end if;

  update public.order_items item
  set warranty_months = product.warranty_months
  from public.products product
  where item.order_id = p_order_id
    and product.id = item.product_id;

  -- Giá sỉ: tổng số lượng (mọi màu) của một sản phẩm trong đơn đạt ngưỡng
  update public.order_items item
  set unit_price = round(item.unit_price * (1 - product.wholesale_percent))::bigint
  from public.products product,
    (
      select product_id, sum(quantity) as qty
      from public.order_items
      where order_id = p_order_id and not is_gift
      group by product_id
    ) totals
  where item.order_id = p_order_id
    and not item.is_gift
    and product.id = item.product_id
    and totals.product_id = item.product_id
    and product.wholesale_percent > 0
    and totals.qty >= product.wholesale_min_qty;

  select coalesce(sum(unit_price * quantity), 0)::bigint into v_item_total
  from public.order_items
  where order_id = p_order_id and not is_gift;

  -- Quà tặng: mốc cao nhất đạt được và còn hàng
  if not exists (select 1 from public.order_items where order_id = p_order_id and is_gift) then
    for v_rule in
      select rule.product_id, rule.quantity, product.name, product.brand, product.category,
        product.image_url, product.price, product.warranty_months
      from public.gift_rules rule
      join public.products product on product.id = rule.product_id
      where rule.active and rule.min_total <= v_item_total
      order by rule.min_total desc
    loop
      select color into v_color
      from public.product_color_stock
      where product_id = v_rule.product_id and stock >= v_rule.quantity
      order by stock desc, color
      limit 1;
      if found then
        insert into public.order_items (
          order_id, product_id, product_name, brand, category, image_url,
          selected_color, original_price, unit_price, quantity, warranty_months, is_gift
        ) values (
          p_order_id, v_rule.product_id, v_rule.name, v_rule.brand, v_rule.category, v_rule.image_url,
          v_color, v_rule.price, 0, v_rule.quantity, v_rule.warranty_months, true
        );
        exit;
      end if;
    end loop;
  end if;

  update public.orders customer_order
  set delivery_zone = p_zone,
      shipping_fee = v_fee,
      discount = customer_order.subtotal - v_item_total,
      total = v_item_total + v_fee,
      deposit_amount = case
        when v_item_total + v_fee >= 20000000
          then (ceil((v_item_total + v_fee) * 0.3 / 1000.0) * 1000)::bigint
        else 0
      end,
      deposit_status = case
        when v_item_total + v_fee >= 20000000 then 'awaiting'
        else 'not_required'
      end
  where customer_order.id = p_order_id;
end;
$$;

revoke all on function public.apply_furniture_terms(uuid, text) from public, anon, authenticated;

-- ---------- Mua lại: bỏ qua quà tặng ----------
create or replace function public.reorder_delivered_order(p_order_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_user_id uuid := (select auth.uid());
  v_order_status text;
  v_product record;
  v_item record;
  v_existing_quantity integer;
  v_target_quantity integer;
  v_added integer;
  v_added_lines integer := 0;
  v_added_quantity integer := 0;
  v_issues jsonb := '[]'::jsonb;
  v_cart jsonb;
begin
  if v_user_id is null then
    raise exception 'AUTH_REQUIRED';
  end if;

  select customer_order.status into v_order_status
  from public.orders customer_order
  where customer_order.id = p_order_id
    and customer_order.user_id = v_user_id
  for update;

  if not found then
    raise exception 'ORDER_NOT_FOUND';
  end if;
  if v_order_status <> 'delivered' then
    raise exception 'REORDER_REQUIRES_DELIVERED_ORDER';
  end if;

  for v_item in
    select item.product_id, item.product_name, item.selected_color, item.quantity
    from public.order_items item
    where item.order_id = p_order_id
      and not item.is_gift -- quà tặng không được mua lại
    order by item.created_at, item.id
  loop
    select product.id, product.colors, product.stock
    into v_product
    from public.products product
    where product.id = v_item.product_id;

    if not found then
      v_issues := v_issues || jsonb_build_array(jsonb_build_object(
        'productId', v_item.product_id,
        'name', v_item.product_name,
        'reason', 'product_unavailable',
        'requestedQuantity', v_item.quantity,
        'addedQuantity', 0
      ));
      continue;
    end if;

    if v_item.selected_color <> all(v_product.colors) then
      v_issues := v_issues || jsonb_build_array(jsonb_build_object(
        'productId', v_item.product_id,
        'name', v_item.product_name,
        'reason', 'color_unavailable',
        'requestedQuantity', v_item.quantity,
        'addedQuantity', 0
      ));
      continue;
    end if;

    select coalesce((
      select cart.quantity
      from public.cart_items cart
      where cart.user_id = v_user_id
        and cart.product_id = v_item.product_id
        and cart.selected_color = v_item.selected_color
    ), 0) into v_existing_quantity;

    if v_product.stock <= v_existing_quantity then
      v_issues := v_issues || jsonb_build_array(jsonb_build_object(
        'productId', v_item.product_id,
        'name', v_item.product_name,
        'reason', case when v_product.stock <= 0 then 'out_of_stock' else 'cart_at_limit' end,
        'requestedQuantity', v_item.quantity,
        'addedQuantity', 0
      ));
      continue;
    end if;

    v_target_quantity := least(v_product.stock, v_existing_quantity + v_item.quantity);
    v_added := v_target_quantity - v_existing_quantity;

    insert into public.cart_items (
      user_id, product_id, selected_color, quantity
    ) values (
      v_user_id, v_item.product_id, v_item.selected_color, v_target_quantity
    )
    on conflict (user_id, product_id, selected_color)
    do update set quantity = excluded.quantity;

    v_added_lines := v_added_lines + 1;
    v_added_quantity := v_added_quantity + v_added;

    if v_added < v_item.quantity then
      v_issues := v_issues || jsonb_build_array(jsonb_build_object(
        'productId', v_item.product_id,
        'name', v_item.product_name,
        'reason', 'quantity_limited',
        'requestedQuantity', v_item.quantity,
        'addedQuantity', v_added
      ));
    end if;
  end loop;

  select coalesce(
    jsonb_agg(
      jsonb_build_object(
        'productId', cart.product_id,
        'selectedColor', cart.selected_color,
        'quantity', cart.quantity
      ) order by cart.created_at
    ),
    '[]'::jsonb
  ) into v_cart
  from public.cart_items cart
  where cart.user_id = v_user_id;

  return jsonb_build_object(
    'addedLines', v_added_lines,
    'addedQuantity', v_added_quantity,
    'issues', v_issues,
    'cart', v_cart
  );
end;
$$;

revoke all on function public.reorder_delivered_order(uuid) from public, anon;
grant execute on function public.reorder_delivered_order(uuid) to authenticated;

-- ---------- Thống kê: tách giá vốn quà tặng, bán chạy không tính quà ----------
-- ---------- Số liệu thống kê (chỉ admin gọi được) ----------
-- Thu: tiền hàng + phí giao của đơn đã giao trong kỳ. Chi: giá vốn của hàng đã giao + tiền cọc phải hoàn.
create or replace function public.admin_dashboard(p_days integer default 30)
returns jsonb
language plpgsql
stable
security definer
set search_path = ''
as $$
declare
  v_from timestamptz := now() - make_interval(days => greatest(coalesce(p_days, 30), 1));
  v_today date := timezone('Asia/Ho_Chi_Minh', now())::date;
  v_unit text := case when coalesce(p_days, 30) <= 31 then 'day' else 'month' end;
  v_result jsonb;
begin
  if not public.is_admin() then
    raise exception 'ADMIN_ONLY';
  end if;

  with period_orders as (
    select * from public.orders where created_at >= v_from
  ),
  delivered as (
    select * from period_orders where status = 'delivered'
  ),
  delivered_items as (
    select item.*, product.cost_price
    from public.order_items item
    join delivered on delivered.id = item.order_id
    join public.products product on product.id = item.product_id
  )
  select jsonb_build_object(
    'days', greatest(coalesce(p_days, 30), 1),
    'summary', jsonb_build_object(
      'revenue', coalesce((select sum(total) from delivered), 0),
      'goodsRevenue', coalesce((select sum(total - shipping_fee) from delivered), 0),
      'shippingRevenue', coalesce((select sum(shipping_fee) from delivered), 0),
      'costOfGoods', coalesce((select sum(cost_price * quantity) from delivered_items), 0),
      -- Giá vốn của quà tặng (đã nằm trong costOfGoods)
      'giftCost', coalesce((select sum(cost_price * quantity) from delivered_items where is_gift), 0),
      'refundedDeposits', coalesce((select sum(deposit_amount) from period_orders where deposit_status = 'refunded'), 0),
      -- Cọc đang giữ: đã nhận cọc nhưng đơn chưa giao xong (giao xong thì cọc tính vào doanh thu)
      'depositsHeld', coalesce((select sum(deposit_amount) from public.orders where deposit_status = 'paid' and status not in ('delivered', 'cancelled')), 0),
      -- Tổng tiền cọc đã nhận của các đơn đặt trong kỳ (kể cả đơn đã giao hoặc đã hoàn cọc)
      'depositsReceived', coalesce((select sum(deposit_amount) from period_orders where deposit_status in ('paid', 'refunded')), 0),
      'openOrderValue', coalesce((select sum(total) from period_orders where status not in ('delivered', 'cancelled')), 0),
      'orderCount', (select count(*) from period_orders),
      'deliveredCount', (select count(*) from delivered),
      'cancelledCount', (select count(*) from period_orders where status = 'cancelled')
    ),
    -- Thu (đơn đã giao) và chi (giá vốn) theo từng ngày, hoặc từng tháng khi xem 12 tháng
    'series', coalesce((
      select jsonb_agg(jsonb_build_object(
        'label', to_char(bucket.start_at, case when v_unit = 'day' then 'DD/MM' else 'MM/YY' end),
        'revenue', coalesce((
          select sum(total) from delivered
          where date_trunc(v_unit, timezone('Asia/Ho_Chi_Minh', delivered.created_at)) = bucket.start_at
        ), 0),
        'cost', coalesce((
          select sum(cost_price * quantity) from delivered_items
          join delivered on delivered.id = delivered_items.order_id
          where date_trunc(v_unit, timezone('Asia/Ho_Chi_Minh', delivered.created_at)) = bucket.start_at
        ), 0)
      ) order by bucket.start_at)
      from generate_series(
        date_trunc(v_unit, timezone('Asia/Ho_Chi_Minh', v_from)),
        date_trunc(v_unit, timezone('Asia/Ho_Chi_Minh', now())),
        ('1 ' || v_unit)::interval
      ) as bucket(start_at)
    ), '[]'::jsonb),
    'statusCounts', coalesce((
      select jsonb_object_agg(status, n) from (select status, count(*) as n from period_orders group by status) counts
    ), '{}'::jsonb),
    'topProducts', coalesce((
      select jsonb_agg(row_to_json(top)::jsonb order by top.quantity desc, top.revenue desc)
      from (
        select product_id as "productId", min(product_name) as name, sum(quantity)::integer as quantity,
          sum(unit_price * quantity)::bigint as revenue, sum(cost_price * quantity)::bigint as cost
        from delivered_items
        where not is_gift
        group by product_id
        order by sum(quantity) desc, sum(unit_price * quantity) desc
        limit 5
      ) top
    ), '[]'::jsonb),
    'categories', coalesce((
      select jsonb_agg(row_to_json(cat)::jsonb order by cat.revenue desc)
      from (
        select category, sum(unit_price * quantity)::bigint as revenue, sum(cost_price * quantity)::bigint as cost
        from delivered_items
        where not is_gift
        group by category
      ) cat
    ), '[]'::jsonb),
    'lowStock', coalesce((
      select jsonb_agg(row_to_json(low)::jsonb order by low.stock, low.name)
      from (
        select product.id as "productId", product.name, color_stock.color, color_stock.stock
        from public.product_color_stock color_stock
        join public.products product on product.id = color_stock.product_id
        where color_stock.stock <= 2
        order by color_stock.stock, product.name
        limit 10
      ) low
    ), '[]'::jsonb),
    -- Đơn sắp giao gom theo ngày + khu vực: cùng ngày, cùng khu vực thì xếp chung một chuyến
    'deliveryPlan', coalesce((
      select jsonb_agg(row_to_json(trip)::jsonb order by trip.date, trip.zone)
      from (
        select installation_date as date, coalesce(delivery_zone, 'unknown') as zone, count(*)::integer as "orderCount",
          sum((select sum(quantity) from public.order_items where order_id = o.id))::integer as "itemCount",
          jsonb_agg(jsonb_build_object('code', code, 'timeSlot', installation_time_slot, 'status', status, 'address', shipping_address)
            order by installation_time_slot, code) as orders
        from public.orders o
        where status in ('pending_confirmation', 'confirmed', 'preparing', 'shipping', 'installing')
          and installation_date >= v_today
        group by installation_date, coalesce(delivery_zone, 'unknown')
        order by installation_date, coalesce(delivery_zone, 'unknown')
        limit 20
      ) trip
    ), '[]'::jsonb)
  ) into v_result;

  return v_result;
end;
$$;

revoke all on function public.admin_dashboard(integer) from public, anon;
grant execute on function public.admin_dashboard(integer) to authenticated;
